-- Primera migración. IF NOT EXISTS permite adoptar una base creada antes de Flyway.
-- No elimina ni modifica registros existentes.
CREATE SEQUENCE IF NOT EXISTS seq_codigo_solicitud START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula VARCHAR(10) NOT NULL,
    nombres VARCHAR(255),
    apellidos VARCHAR(255),
    telefono VARCHAR(255),
    correo VARCHAR(255),
    estado VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    password VARCHAR(255) NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    correo VARCHAR(120),
    rol VARCHAR(20) NOT NULL,
    activo BOOLEAN NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    CONSTRAINT uk_usuario_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS solicitudes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_solicitud VARCHAR(30) NOT NULL UNIQUE,
    estado_civil VARCHAR(255),
    ocupacion VARCHAR(255),
    direccion VARCHAR(255),
    ingresos_mensuales DOUBLE PRECISION,
    egresos_mensuales DOUBLE PRECISION,
    nivel_endeudamiento DOUBLE PRECISION,
    empresa VARCHAR(255),
    antiguedad_laboral VARCHAR(255),
    capacidad_pago DOUBLE PRECISION,
    ventas_anuales DOUBLE PRECISION,
    actividad_economica VARCHAR(255),
    fuente_pago VARCHAR(255),
    tipo_credito VARCHAR(255),
    subsegmento_credito VARCHAR(255),
    producto_credito VARCHAR(255),
    monto DOUBLE PRECISION,
    plazo_meses INTEGER,
    estado VARCHAR(255),
    destino_credito VARCHAR(255),
    fecha_solicitud TIMESTAMP,
    observacion_decision VARCHAR(1500),
    fecha_decision TIMESTAMP,
    cliente_id BIGINT NOT NULL REFERENCES clientes(id)
);

CREATE TABLE IF NOT EXISTS documentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento VARCHAR(255),
    nombre_archivo VARCHAR(255),
    ruta_archivo VARCHAR(255),
    estado VARCHAR(255),
    fecha_carga TIMESTAMP,
    solicitud_id BIGINT NOT NULL REFERENCES solicitudes(id)
);

CREATE TABLE IF NOT EXISTS evaluaciones_riesgo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT NOT NULL REFERENCES solicitudes(id),
    score_ia INTEGER,
    probabilidad_mora DOUBLE PRECISION,
    confianza_modelo DOUBLE PRECISION,
    nivel_riesgo VARCHAR(255),
    recomendacion VARCHAR(255),
    modelo_utilizado VARCHAR(255),
    estado VARCHAR(255),
    explicacion VARCHAR(2000),
    fecha_evaluacion TIMESTAMP
);

CREATE TABLE IF NOT EXISTS codigos_verificacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    codigo_hash VARCHAR(255) NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_expiracion TIMESTAMP NOT NULL,
    intentos INTEGER NOT NULL,
    utilizado BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    titulo VARCHAR(150) NOT NULL,
    mensaje VARCHAR(1000) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    leida BOOLEAN NOT NULL,
    entidad_tipo VARCHAR(50),
    entidad_id BIGINT,
    ruta VARCHAR(255),
    fecha_creacion TIMESTAMP NOT NULL,
    fecha_lectura TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_solicitudes_cliente ON solicitudes(cliente_id);
CREATE INDEX IF NOT EXISTS idx_documentos_solicitud ON documentos(solicitud_id);
CREATE INDEX IF NOT EXISTS idx_evaluaciones_solicitud ON evaluaciones_riesgo(solicitud_id);
CREATE INDEX IF NOT EXISTS idx_codigos_usuario ON codigos_verificacion(usuario_id);
CREATE INDEX IF NOT EXISTS idx_notificacion_usuario ON notificaciones(usuario_id);
CREATE INDEX IF NOT EXISTS idx_notificacion_usuario_leida ON notificaciones(usuario_id, leida);

-- Las bases de demostración antiguas pueden contener cédulas repetidas.
-- El servicio impide nuevos duplicados; el índice se instala si los datos lo permiten.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM clientes GROUP BY cedula HAVING COUNT(*) > 1
    ) THEN
        CREATE UNIQUE INDEX IF NOT EXISTS ux_clientes_cedula ON clientes(cedula);
    END IF;
END $$;
